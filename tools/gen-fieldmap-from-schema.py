#!/usr/bin/env python3
"""Regenerate apps/api/src/modules/conmas/fieldMap.generated.ts from the view's column list.

Input : docs/03-database/view_report_27537.schema.tsv   (lines: "<n>_<t|n|d>\\t<field name>", dari pg information_schema)
Output: apps/api/src/modules/conmas/fieldMap.generated.ts
Run   : python tools/gen-fieldmap-from-schema.py
Aturan: blok jam dimulai di kolom 'JAM ...'; slot dimulai di 'QTY PCS'; kolom lain mengisi slot terakhir.
"""
import re, json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
rows = [l.rstrip('\n').split('\t') for l in (root / 'docs/03-database/view_report_27537.schema.tsv').read_text(encoding='utf-8').splitlines() if l.strip()]
col = lambda i: 'cluster_1_' + i
HDR = {'date': 'productionDate', 'NO. MESIN': 'machineNo', 'SHIFT': 'shift', 'GROUP': 'group', 'JUMLAH CAVITY': 'cavity',
       'OTUPUT PLAN 1': 'outputPlan', 'LEADER': 'leaderNik', 'CELL LEADER': 'cellLeaderNik', 'DP NO. 1': 'dpNo',
       'OUTPUT ACTUAL 1': 'outputActual', 'PRODUCT NAME 1': 'productName', 'PO NO 1': 'poNo', 'TEKNISI': 'technicianNik',
       'OPERATOR': 'operatorNik', 'CT ACTUAL 1': 'ctActual', 'NG QTY 1': 'ngQty', 'OUTPUT GROSS PCS 1': 'outputGross',
       'PROD OPT TIME': 'plannedMinutes'}
SLOT = {'MENIT': 'minutes', 'KATEGORI': 'category', 'DETAIL': 'detail', 'REJECT': 'reject', 'QTY REJECT': 'rejectQty', 'KRITERIA': 'kriteria'}
header, blocks, cur, slot, in_blocks = {}, [], None, None, False
for i, n in rows:
    if n.startswith('JAM '):
        in_blocks = True; cur = {'label': col(i), 'slots': []}; blocks.append(cur); slot = None; continue
    if n == 'PROD OPT TIME': in_blocks = False
    if not in_blocks:
        if n in HDR: header[HDR[n]] = col(i)
        continue
    if re.fullmatch(r'\d\d\.\d\d-\d\d\.\d\d', n): continue  # label numerik per blok, tidak dipakai
    if n == 'QTY PCS': slot = {'qty': col(i)}; cur['slots'].append(slot); continue
    key = SLOT['QTY REJECT' if n.startswith('QTY REJECT') else n.split(' ')[0]]
    assert slot is not None and key not in slot, (i, n)
    slot[key] = col(i)
missing = [v for v in HDR.values() if v not in header]
assert not missing, missing
order = ['productionDate','machineNo','shift','group','cavity','outputPlan','leaderNik','cellLeaderNik','dpNo','outputActual','productName','poNo','technicianNik','operatorNik','ctActual','ngQty','outputGross','plannedMinutes']
head = '\n'.join(f"  {k}: '{header[k]}'," for k in order)
out = f'''/* GENERATED by tools/gen-fieldmap-from-schema.py from docs/03-database/view_report_27537.schema.tsv (owner: view baru 2026-11-18).
 * Domain meaning of every column is PROPOSED until confirmed per row by the owner (STATE §10).
 * Physical cluster_* names MUST NOT leave apps/api (ADR-011/021). */
/** minutes/category bisa tidak ada di view (mis. blok 11 slot 3): slot tetap dibaca untuk qty/detail/reject. */
export interface SlotColumns {{ qty: string; minutes?: string; category?: string; detail?: string; reject?: string; rejectQty?: string; kriteria?: string }}
export interface HourBlockColumns {{ label: string; slots: SlotColumns[] }}
export const HEADER_COLUMNS = {{
{head}
}} as const;
export const HOUR_BLOCKS: readonly HourBlockColumns[] = {json.dumps(blocks, indent=1)};
'''
(root / 'apps/api/src/modules/conmas/fieldMap.generated.ts').write_text(out, encoding='utf-8')
print('ok', len(blocks), 'blocks')
